using System.Data.Common;
using System.Text.Json.Nodes;
using Microsoft.Data.Sqlite;
using Npgsql;

namespace Pluff.AspNet.Runtime;

public sealed class TatemonoDatabase
{
    private readonly string _backendDirectory;
    private readonly string _driver;

    public TatemonoDatabase(string backendDirectory)
    {
        _backendDirectory = backendDirectory;
        _driver = Environment.GetEnvironmentVariable("ARKZEN_DB_DRIVER") == "pgsql" ? "pgsql" : "sqlite";
    }

    public async Task<DbConnection> OpenAsync(string slug, CancellationToken cancellationToken)
    {
        DbConnection connection;
        if (_driver == "pgsql")
        {
            var databaseName = DatabaseName(slug);
            await EnsurePostgresDatabaseAsync(databaseName, cancellationToken);
            connection = new NpgsqlConnection(PostgresConnectionString(databaseName));
        }
        else
        {
            var directory = Path.Combine(_backendDirectory, "database", "arkzen");
            Directory.CreateDirectory(directory);
            connection = new SqliteConnection($"Data Source={Path.Combine(directory, $"{slug}.sqlite")}");
        }

        await connection.OpenAsync(cancellationToken);
        return connection;
    }

    public async Task ApplySchemaAsync(DbConnection connection, string slug, JsonArray databases, CancellationToken cancellationToken)
    {
        foreach (var definition in databases.OfType<JsonObject>())
        {
            var table = RequiredIdentifier(StringValue(definition["table"]), "database table");
            var columns = definition["columns"] as JsonObject ?? new JsonObject();
            var tableName = PrefixedTable(slug, table);
            var definitions = new List<string>();
            if (!columns.Any(column => column.Value?["primary"]?.GetValue<bool>() == true))
                definitions.Add(_driver == "pgsql" ? "\"id\" BIGSERIAL PRIMARY KEY" : "\"id\" INTEGER PRIMARY KEY AUTOINCREMENT");

            foreach (var (name, value) in columns)
            {
                var column = RequiredIdentifier(name, "column");
                var config = value as JsonObject ?? new JsonObject();
                var type = StringValue(config["type"]) ?? "string";
                var sqlType = SqlType(type, config);
                var primary = config["primary"]?.GetValue<bool>() == true;
                var nullable = config["nullable"]?.GetValue<bool>() == true;
                var pieces = new List<string> { Quote(column), sqlType };
                if (primary) pieces.Add("PRIMARY KEY");
                if (primary && config["autoIncrement"]?.GetValue<bool>() != false &&
                    (_driver == "pgsql" ? type is "integer" or "bigInteger" : type == "integer"))
                    pieces.Add(_driver == "pgsql" ? "GENERATED BY DEFAULT AS IDENTITY" : "AUTOINCREMENT");
                if (!nullable && !primary) pieces.Add("NOT NULL");
                if (config["unique"]?.GetValue<bool>() == true) pieces.Add("UNIQUE");
                if (config["default"] is JsonValue defaultValue)
                    pieces.Add($"DEFAULT {SqlLiteral(defaultValue)}");
                definitions.Add(string.Join(' ', pieces));
            }

            if (definition["timestamps"]?.GetValue<bool>() != false)
            {
                var timestampType = _driver == "pgsql" ? "TIMESTAMPTZ" : "TEXT";
                if (!columns.ContainsKey("created_at")) definitions.Add($"\"created_at\" {timestampType} NULL");
                if (!columns.ContainsKey("updated_at")) definitions.Add($"\"updated_at\" {timestampType} NULL");
            }
            if (definition["softDeletes"]?.GetValue<bool>() == true && !columns.ContainsKey("deleted_at"))
                definitions.Add($"\"deleted_at\" {(_driver == "pgsql" ? "TIMESTAMPTZ" : "TEXT")} NULL");

            await using var command = connection.CreateCommand();
            command.CommandText = $"CREATE TABLE IF NOT EXISTS {Quote(tableName)} ({string.Join(", ", definitions)})";
            await command.ExecuteNonQueryAsync(cancellationToken);
            await AddMissingColumnsAsync(connection, tableName, columns, cancellationToken);
        }
    }

    public async Task EnsureAuthTablesAsync(DbConnection connection, string slug, JsonNode? authSeed, CancellationToken cancellationToken)
    {
        var users = Quote(PrefixedTable(slug, "users"));
        var tokens = Quote(PrefixedTable(slug, "personal_access_tokens"));
        var idType = _driver == "pgsql" ? "BIGSERIAL" : "INTEGER";
        var autoIncrement = _driver == "pgsql" ? "" : " PRIMARY KEY AUTOINCREMENT";
        var userId = _driver == "pgsql" ? "\"id\" BIGSERIAL PRIMARY KEY" : "\"id\" INTEGER PRIMARY KEY AUTOINCREMENT";
        var tokenId = userId;
        var timestamp = _driver == "pgsql" ? "TIMESTAMPTZ" : "TEXT";

        await using (var command = connection.CreateCommand())
        {
            command.CommandText = $"""
                CREATE TABLE IF NOT EXISTS {users} (
                    "id" {idType}{autoIncrement}{(_driver == "pgsql" ? " PRIMARY KEY" : "")},
                    "name" VARCHAR(255) NOT NULL,
                    "email" VARCHAR(255) NOT NULL UNIQUE,
                    "email_verified_at" {timestamp} NULL,
                    "password" TEXT NOT NULL,
                    "role" VARCHAR(20) NOT NULL DEFAULT 'user',
                    "created_at" {timestamp} NULL,
                    "updated_at" {timestamp} NULL
                )
                """;
            await command.ExecuteNonQueryAsync(cancellationToken);
        }
        await AddMissingColumnsAsync(connection, PrefixedTable(slug, "users"), new JsonObject
        {
            ["name"] = new JsonObject { ["type"] = "string", ["nullable"] = true },
            ["email"] = new JsonObject { ["type"] = "string", ["nullable"] = true },
            ["email_verified_at"] = new JsonObject { ["type"] = "timestamp", ["nullable"] = true },
            ["password"] = new JsonObject { ["type"] = "text", ["nullable"] = true },
            ["role"] = new JsonObject { ["type"] = "string", ["length"] = 20, ["nullable"] = true },
            ["created_at"] = new JsonObject { ["type"] = "timestamp", ["nullable"] = true },
            ["updated_at"] = new JsonObject { ["type"] = "timestamp", ["nullable"] = true }
        }, cancellationToken);

        await using (var command = connection.CreateCommand())
        {
            command.CommandText = $"""
                CREATE TABLE IF NOT EXISTS {tokens} (
                    {tokenId},
                    "tokenable_type" VARCHAR(255) NOT NULL,
                    "tokenable_id" BIGINT NOT NULL,
                    "name" VARCHAR(255) NOT NULL,
                    "token" VARCHAR(64) NOT NULL UNIQUE,
                    "abilities" TEXT NULL,
                    "last_used_at" {timestamp} NULL,
                    "expires_at" {timestamp} NULL,
                    "created_at" {timestamp} NULL,
                    "updated_at" {timestamp} NULL
                )
                """;
            await command.ExecuteNonQueryAsync(cancellationToken);
        }
        await AddMissingColumnsAsync(connection, PrefixedTable(slug, "personal_access_tokens"), new JsonObject
        {
            ["tokenable_type"] = new JsonObject { ["type"] = "string", ["nullable"] = true },
            ["tokenable_id"] = new JsonObject { ["type"] = "bigInteger", ["nullable"] = true },
            ["name"] = new JsonObject { ["type"] = "string", ["nullable"] = true },
            ["token"] = new JsonObject { ["type"] = "string", ["length"] = 64, ["nullable"] = true },
            ["abilities"] = new JsonObject { ["type"] = "text", ["nullable"] = true },
            ["last_used_at"] = new JsonObject { ["type"] = "timestamp", ["nullable"] = true },
            ["expires_at"] = new JsonObject { ["type"] = "timestamp", ["nullable"] = true },
            ["created_at"] = new JsonObject { ["type"] = "timestamp", ["nullable"] = true },
            ["updated_at"] = new JsonObject { ["type"] = "timestamp", ["nullable"] = true }
        }, cancellationToken);

        var seedUsers = authSeed is JsonArray array
            ? array
            : authSeed?["users"] as JsonArray;
        if (seedUsers is null) return;
        foreach (var user in seedUsers.OfType<JsonObject>())
        {
            var email = StringValue(user["email"]);
            if (string.IsNullOrWhiteSpace(email)) continue;
            await using var command = connection.CreateCommand();
            command.CommandText = $"""
                INSERT INTO {users} ("name", "email", "password", "role", "created_at", "updated_at")
                VALUES (@name, @email, @password, @role, @created, @updated)
                ON CONFLICT ("email") DO UPDATE SET
                    "name" = excluded."name",
                    "password" = excluded."password",
                    "role" = excluded."role",
                    "updated_at" = excluded."updated_at"
                """;
            var now = DateTime.UtcNow;
            AddParameter(command, "@name", StringValue(user["name"]) ?? email);
            AddParameter(command, "@email", email);
            AddParameter(command, "@password", PasswordHash.Create(StringValue(user["password"]) ?? "password"));
            AddParameter(command, "@role", StringValue(user["role"]) ?? "user");
            AddParameter(command, "@created", now);
            AddParameter(command, "@updated", now);
            await command.ExecuteNonQueryAsync(cancellationToken);
        }
    }

    public async Task SeedTablesAsync(DbConnection connection, string slug, JsonArray databases, CancellationToken cancellationToken)
    {
        foreach (var definition in databases.OfType<JsonObject>())
        {
            if (definition["seeder"]?["data"] is not JsonArray rows || rows.Count == 0) continue;
            var table = Quote(PrefixedTable(slug, StringValue(definition["table"]) ?? ""));
            await using (var clear = connection.CreateCommand())
            {
                clear.CommandText = $"DELETE FROM {table}";
                await clear.ExecuteNonQueryAsync(cancellationToken);
            }

            var timestamps = definition["timestamps"]?.GetValue<bool>() != false;
            foreach (var row in rows.OfType<JsonObject>())
            {
                var values = row.ToDictionary(pair => pair.Key, pair => ToDbValue(pair.Value), StringComparer.Ordinal);
                var now = DateTime.UtcNow;
                if (timestamps)
                {
                    values.TryAdd("created_at", now);
                    values.TryAdd("updated_at", now);
                }
                if (values.Count == 0) continue;

                await using var command = connection.CreateCommand();
                var columns = values.Keys.Select(name => Quote(RequiredIdentifier(name, "seed column"))).ToArray();
                command.CommandText = $"INSERT INTO {table} ({string.Join(", ", columns)}) VALUES ({string.Join(", ", values.Keys.Select((_, index) => $"@p{index}"))})";
                var parameterIndex = 0;
                foreach (var value in values.Values) AddParameter(command, $"@p{parameterIndex++}", value);
                await command.ExecuteNonQueryAsync(cancellationToken);
            }
        }
    }

    public async Task RemoveAsync(string slug, CancellationToken cancellationToken)
    {
        if (_driver == "pgsql")
        {
            var databaseName = DatabaseName(slug);
            await using var connection = new NpgsqlConnection(PostgresConnectionString("postgres"));
            await connection.OpenAsync(cancellationToken);
            await using var command = connection.CreateCommand();
            command.CommandText = $"DROP DATABASE IF EXISTS {Quote(databaseName)} WITH (FORCE)";
            await command.ExecuteNonQueryAsync(cancellationToken);
            return;
        }

        var file = Path.Combine(_backendDirectory, "database", "arkzen", $"{slug}.sqlite");
        if (File.Exists(file)) File.Delete(file);
    }

    public static string PrefixedTable(string slug, string table) =>
        RequiredIdentifier($"{slug.Replace('-', '_')}_{table}", "table");

    private async Task AddMissingColumnsAsync(DbConnection connection, string table, JsonObject columns, CancellationToken cancellationToken)
    {
        if (columns.Count == 0) return;
        var existing = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        await using (var command = connection.CreateCommand())
        {
            command.CommandText = _driver == "pgsql"
                ? "SELECT column_name FROM information_schema.columns WHERE table_name = @table"
                : $"PRAGMA table_info({Quote(table)})";
            AddParameter(command, "@table", table);
            await using var reader = await command.ExecuteReaderAsync(cancellationToken);
            while (await reader.ReadAsync(cancellationToken))
                existing.Add(reader.GetString(_driver == "pgsql" ? 0 : 1));
        }

        foreach (var (name, value) in columns)
        {
            if (existing.Contains(name)) continue;
            var config = value as JsonObject ?? new JsonObject();
            var type = StringValue(config["type"]) ?? "string";
            var nullable = config["nullable"]?.GetValue<bool>() == true;
            await using var command = connection.CreateCommand();
            command.CommandText = $"ALTER TABLE {Quote(table)} ADD COLUMN {Quote(RequiredIdentifier(name, "column"))} {SqlType(type, config)}{(nullable ? "" : " NULL")}";
            await command.ExecuteNonQueryAsync(cancellationToken);
        }
    }

    private async Task EnsurePostgresDatabaseAsync(string databaseName, CancellationToken cancellationToken)
    {
        await using var connection = new NpgsqlConnection(PostgresConnectionString("postgres"));
        await connection.OpenAsync(cancellationToken);
        await using var check = connection.CreateCommand();
        check.CommandText = "SELECT 1 FROM pg_database WHERE datname = @name";
        AddParameter(check, "@name", databaseName);
        if (await check.ExecuteScalarAsync(cancellationToken) is not null) return;
        await using var create = connection.CreateCommand();
        create.CommandText = $"CREATE DATABASE {Quote(databaseName)}";
        await create.ExecuteNonQueryAsync(cancellationToken);
    }

    private string PostgresConnectionString(string database) => new NpgsqlConnectionStringBuilder
    {
        Host = Environment.GetEnvironmentVariable("DB_HOST") ?? "127.0.0.1",
        Port = int.TryParse(Environment.GetEnvironmentVariable("DB_PORT"), out var port) ? port : 5432,
        Username = Environment.GetEnvironmentVariable("DB_USERNAME") ?? "postgres",
        Password = Environment.GetEnvironmentVariable("DB_PASSWORD") ?? "",
        Database = database
    }.ConnectionString;

    private static string DatabaseName(string slug)
    {
        var prefix = Environment.GetEnvironmentVariable("ARKZEN_DB_PREFIX") ?? "pluff";
        return RequiredIdentifier($"{prefix}_{slug.Replace('-', '_')}".ToLowerInvariant(), "database");
    }

    private string SqlType(string type, JsonObject config) => type switch
    {
        "integer" or "foreignId" => _driver == "pgsql" ? "BIGINT" : "INTEGER",
        "bigInteger" => "BIGINT",
        "decimal" => $"DECIMAL({IntegerValue(config["precision"], 8)},{IntegerValue(config["scale"], 2)})",
        "float" => "REAL",
        "boolean" => _driver == "pgsql" ? "BOOLEAN" : "INTEGER",
        "date" => "DATE",
        "datetime" or "timestamp" => _driver == "pgsql" ? "TIMESTAMPTZ" : "TEXT",
        "json" => _driver == "pgsql" ? "JSONB" : "TEXT",
        "text" or "longText" => "TEXT",
        "uuid" => _driver == "pgsql" ? "UUID" : "TEXT",
        _ => $"VARCHAR({IntegerValue(config["length"], 255)})"
    };

    private static string SqlLiteral(JsonValue value)
    {
        if (value.TryGetValue<bool>(out var boolean)) return boolean ? "TRUE" : "FALSE";
        if (value.TryGetValue<int>(out var smallInteger)) return smallInteger.ToString(System.Globalization.CultureInfo.InvariantCulture);
        if (value.TryGetValue<long>(out var integer)) return integer.ToString(System.Globalization.CultureInfo.InvariantCulture);
        if (value.TryGetValue<double>(out var number)) return number.ToString(System.Globalization.CultureInfo.InvariantCulture);
        var text = value.ToString().Replace("'", "''", StringComparison.Ordinal);
        return $"'{text}'";
    }

    private static int IntegerValue(JsonNode? value, int fallback) =>
        int.TryParse(StringValue(value), out var number) && number > 0 ? number : fallback;

    private static string? StringValue(JsonNode? value) => value is JsonValue jsonValue ? jsonValue.ToString() : null;

    private static object? ToDbValue(JsonNode? value)
    {
        if (value is null) return null;
        if (value is JsonValue jsonValue)
        {
            if (jsonValue.TryGetValue<string>(out var text)) return text;
            if (jsonValue.TryGetValue<bool>(out var boolean)) return boolean;
            if (jsonValue.TryGetValue<int>(out var smallInteger)) return smallInteger;
            if (jsonValue.TryGetValue<long>(out var integer)) return integer;
            if (jsonValue.TryGetValue<double>(out var number)) return number;
        }
        return value.ToJsonString();
    }

    private static string RequiredIdentifier(string? value, string label)
    {
        if (value is null || !System.Text.RegularExpressions.Regex.IsMatch(value, "^[A-Za-z_][A-Za-z0-9_]*$"))
            throw new InvalidOperationException($"Invalid {label} identifier.");
        return value;
    }

    internal static string Quote(string value) => $"\"{RequiredIdentifier(value, "SQL")}\"";

    internal static void AddParameter(DbCommand command, string name, object? value)
    {
        var parameter = command.CreateParameter();
        parameter.ParameterName = name;
        parameter.Value = value ?? DBNull.Value;
        command.Parameters.Add(parameter);
    }
}
