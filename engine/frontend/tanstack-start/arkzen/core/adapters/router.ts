import { useRouter, useLocation } from '@tanstack/react-router'

export interface ArkzenRouter {
  replace: (path: string) => void
  push:    (path: string) => void
}

export function useArkzenRouter(): ArkzenRouter {
  const router = useRouter()
  return {
    replace: (path: string) => router.navigate({ to: path, replace: true }),
    push:    (path: string) => router.navigate({ to: path }),
  }
}

export function useArkzenPathname(): string {
  return useLocation().pathname
}

// TanStack-compatible useNavigate (wraps @tanstack/react-router's useRouter)
// Exported for use in components generated by normalizeForTanStack
export function useNavigate() {
  const router = useRouter()
  return (path: string) => router.navigate({ to: path })
}

// TanStack-compatible useLocation (re-export for consistency)
export { useLocation }

